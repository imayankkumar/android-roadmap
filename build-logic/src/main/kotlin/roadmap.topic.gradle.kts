/*
 * Shared setup for every module in this repo.
 *
 *   ./gradlew :<topic>:test        run the tests that prove each claim
 *   ./gradlew :<topic>:decompile   write readable Java to <topic>/decompiled/
 *   ./gradlew :<topic>:bytecode    print the raw bytecode (javap -c -p)
 */
plugins {
    kotlin("jvm")
}

val libs = the<VersionCatalogsExtension>().named("libs")
fun lib(alias: String) = libs.findLibrary(alias).get()

kotlin {
    jvmToolchain(21)
}

dependencies {
    testImplementation(platform(lib("junit-bom")))
    testImplementation(kotlin("test"))
    testImplementation(lib("junit-jupiter"))
    testRuntimeOnly(lib("junit-platform-launcher"))
}

tasks.test {
    useJUnitPlatform()
    testLogging {
        events("passed", "failed")
    }
}

val compiledClasses = sourceSets.main.map { it.output.classesDirs }

// Decompiler on its own classpath, so it never mixes with the code we teach.
val vineflower = configurations.create("vineflower")
dependencies {
    vineflower(lib("vineflower"))
}

val vineflowerOutput = layout.buildDirectory.dir("vineflower")

val runVineflower = tasks.register<JavaExec>("runVineflower") {
    description = "Decompiles this module's classes to Java with Vineflower."
    dependsOn(tasks.named("classes"))
    classpath = vineflower
    mainClass = "org.jetbrains.java.decompiler.main.decompiler.ConsoleDecompiler"
    val inputDirs = compiledClasses
    val outputDir = vineflowerOutput
    inputs.files(inputDirs)
    outputs.dir(outputDir)
    doFirst { outputDir.get().asFile.apply { deleteRecursively(); mkdirs() } }
    argumentProviders.add(CommandLineArgumentProvider {
        listOf(
            "--kt-enable=false",     // show the Java the JVM runs, not Kotlin rebuilt from metadata
            "--indent-string=    ",  // 4 spaces, like the Kotlin code
            "--silent",
        ) + inputDirs.get().files.filter { it.exists() }.map { it.absolutePath } +
            outputDir.get().asFile.absolutePath
    })
}

val kotlinVersion = libs.findVersion("kotlin").get().requiredVersion
val moduleName = project.name

tasks.register<Sync>("decompile") {
    group = "roadmap"
    description = "Writes readable Java for this module to decompiled/."
    from(runVineflower)
    into(layout.projectDirectory.dir("decompiled"))
    include("**/*.java")
    includeEmptyDirs = false
    // Kotlin's @Metadata and @SourceDebugExtension blocks are long encoded strings for the
    // compiler and debugger. They hide the code we want to look at, so we drop them.
    eachFile {
        filter(KotlinNoiseFilter::class.java)
    }
    val header = "// Generated by ./gradlew :$moduleName:decompile (Kotlin $kotlinVersion, Vineflower).\n" +
        "// Kotlin metadata annotations are removed. Do not edit by hand.\n\n"
    doLast {
        destinationDir.walkTopDown().filter { it.isFile && it.extension == "java" }.forEach { file ->
            file.writeText(header + file.readText())
        }
    }
}

tasks.register<Exec>("bytecode") {
    group = "roadmap"
    description = "Prints the raw bytecode of this module (javap -c -p)."
    dependsOn(tasks.named("classes"))
    val javap = javaToolchains.launcherFor { languageVersion = JavaLanguageVersion.of(21) }
        .map { it.metadata.installationPath.file("bin/javap").asFile.absolutePath }
    val classFiles = compiledClasses.map { dirs -> dirs.asFileTree.matching { include("**/*.class") }.files }
    executable = "javap"
    doFirst {
        executable = javap.get()
        args(listOf("-c", "-p") + classFiles.get().sorted().map { it.absolutePath })
    }
}
